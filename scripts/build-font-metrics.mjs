// Builds packages/figma/src/font-data.js: the names of every Google Fonts family, and how wide the popular text families set a
// sample sentence (measured in Chrome at 400 and 700). The converter uses it to choose a free stand-in for a font that is not on Google
// Fonts: it measures the real font from Figma's own text widths, then picks the free font that sets text at the same width.
//   node scripts/build-font-metrics.mjs          (needs Chrome and a network)
// Source of the family list: https://fonts.google.com/metadata/fonts (public). Fonts are loaded from Google Fonts for measuring.
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { pathToFileURL } from "node:url";

const SAMPLE = "The quick brown fox jumps over the lazy dog. Pack my box with five dozen liquor jugs 0123456789";
const TOP = 220; // the most popular families of each kind that are measured
const out = path.resolve(import.meta.dirname, "../packages/figma/src/font-data.js");
const chrome = ["/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser"].find(fs.existsSync);
if (!chrome) throw new Error("Chrome not found");

const raw = await (await fetch("https://fonts.google.com/metadata/fonts")).text();
const list = JSON.parse(raw.slice(raw.indexOf("{"))).familyMetadataList;
const kind = { "Sans Serif": "sans", Serif: "serif", Monospace: "mono" };
const candidates = list
    .filter((f) => kind[f.category] && f.fonts && f.fonts["400"])
    .sort((a, b) => a.popularity - b.popularity) // 1 is the most popular
    .slice(0, TOP * 2)
    .map((f) => ({ name: f.family, kind: kind[f.category], weights: ["400", "700"].filter((w) => f.fonts[w] || (f.axes || []).some((a) => a.tag === "wght" && a.min <= Number(w) && a.max >= Number(w))) }));

const dir = fs.mkdtempSync(path.join(os.tmpdir(), "font-metrics-"));
const page = path.join(dir, "m.html");
fs.writeFileSync(page, `<!doctype html><meta charset="utf-8"><body><pre id="r">pending</pre><script>
const list = ${JSON.stringify(candidates)}, SAMPLE = ${JSON.stringify(SAMPLE)};
const ctx = document.createElement("canvas").getContext("2d");
(async () => {
  const result = [];
  for (const f of list) {
    const link = document.createElement("link"); link.rel = "stylesheet";
    link.href = "https://fonts.googleapis.com/css2?family=" + f.name.replace(/ /g, "+") + ":wght@" + f.weights.join(";") + "&display=block";
    const sheet = new Promise((resolve) => { link.onload = resolve; link.onerror = resolve; setTimeout(resolve, 8000); });
    document.head.appendChild(link);
    await sheet; // the font can only be asked for once its stylesheet is in
    const row = { name: f.name, kind: f.kind };
    try {
      for (const w of f.weights) {
        const loaded = await document.fonts.load(w + " 100px '" + f.name + "'", SAMPLE);
        if (!loaded.length) throw new Error("font did not load");
        ctx.font = w + " 100px '" + f.name + "'";
        row["w" + w] = Math.round((ctx.measureText(SAMPLE).width / (100 * SAMPLE.length)) * 10000) / 10000;
      }
    } catch (e) { row.error = String(e); }
    result.push(row);
  }
  document.getElementById("r").textContent = JSON.stringify(result);
})();
</script>`);
console.log(`measuring ${candidates.length} families in Chrome...`);
const r = spawnSync(chrome, ["--headless=new", "--disable-gpu", "--allow-file-access-from-files", "--virtual-time-budget=600000", `--user-data-dir=${path.join(dir, "profile")}`, "--dump-dom", pathToFileURL(page).href], { encoding: "utf8", maxBuffer: 1 << 28 });
const m = /<pre id="r">([\s\S]*?)<\/pre>/.exec(r.stdout || "");
if (!m || m[1] === "pending") throw new Error("Chrome did not finish measuring: " + (r.stderr || "").slice(0, 300));
const measured = JSON.parse(m[1].replace(/&quot;/g, '"').replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">")).filter((x) => !x.error && x.w400);
const base = new Map(measured.map((x) => [x.name, x]));
console.log(`${measured.length} measured`);
if (new Set(measured.map((x) => x.w400)).size < 20) throw new Error("the fonts did not load: almost every width is the same");

const names = list.map((f) => f.family).sort();
const rows = measured.sort((a, b) => a.name.localeCompare(b.name)).map((x) => [x.name, x.kind, x.w400, x.w700 ?? x.w400]);
fs.writeFileSync(out, `// Generated by scripts/build-font-metrics.mjs from Google Fonts (${new Date().toISOString().slice(0, 10)}). Do not edit by hand.
// GOOGLE_FAMILIES: every family Google Fonts serves. CANDIDATES: [family, kind (sans|serif|mono), average advance per character as a share
// of the font size at weight 400, and at 700] for the popular text families, measured on one sample sentence.
export const GOOGLE_FAMILIES = ${JSON.stringify(names.join("|"))}.split("|");
export const CANDIDATES = ${JSON.stringify(rows)};
export const MEASURE_SAMPLE_LENGTH = ${SAMPLE.length};
`);
console.log("written", out, fs.statSync(out).size, "bytes");
fs.rmSync(dir, { recursive: true, force: true });
